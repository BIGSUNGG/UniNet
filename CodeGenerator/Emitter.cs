        public static string Emit(List<TypeModel> models, string assemblyName)
        {
            // Generated code for library assemblies (UniNet.*) is isolated in a separate namespace —
            // this avoids name collisions (CS0433) with registration classes in game assemblies; registration is triggered by the RuntimeInitializeOnLoadMethod itself.
            bool isLibrary = assemblyName is "UniNet.Core" or "UniNet.Unity";   // isolate runtime libraries only (test and game assemblies keep public registration)
            string ns = isLibrary ? "UniNet.Generated.Hosting" : "UniNet.Generated";
            string regVisibility = isLibrary ? "internal" : "public";
            string regType = isLibrary ? "__UniNetRegistration_Host" : "__UniNetRegistration";

            var sb = new StringBuilder(24 * 1024);
            sb.AppendLine($"// <auto-generated>Generated by the UniNet code generator ({assemblyName}) — do not edit manually</auto-generated>");
            sb.AppendLine();
            sb.AppendLine("#pragma warning disable CS0618");
            sb.AppendLine();

            EmitHubs(sb, models, ns, regVisibility, regType, isLibrary);
            sb.AppendLine();
            EmitReplicationHandlers(sb, models, ns);
            sb.AppendLine();
            EmitTypePartials(sb, models, ns);

            return sb.ToString();
        }

