                sb.AppendLine("        public override (byte[] Owner, byte[] Others) CompareAndWriteDelta(global::UniNet.Core.Hosting.NetworkServer.SubObjectEntry sub)");
                sb.AppendLine("        {");
                sb.AppendLine($"            var o = ({TypeDisplay2(m)})sub.Instance;");
                sb.AppendLine($"            byte[] owner = {TypeDisplay2(m)}.__UniNetWriteDelta(o, sub.Snapshot, {TypeDisplay2(m)}.__UniNetDeltaMaskOwner);");
                sb.AppendLine($"            byte[] others = {TypeDisplay2(m)}.__UniNetDeltaMaskOther == {TypeDisplay2(m)}.__UniNetDeltaMaskOwner");
                sb.AppendLine($"                ? owner   // no conditional fields — reuse the same payload (computed once on the hot path)");
                sb.AppendLine($"                : {TypeDisplay2(m)}.__UniNetWriteDelta(o, sub.Snapshot, {TypeDisplay2(m)}.__UniNetDeltaMaskOther);");
                sb.AppendLine($"            if (owner != null || others != null) sub.Snapshot = {TypeDisplay2(m)}.__UniNetSnapshot(o);");
                sb.AppendLine("            return (owner, others);");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine("        public override byte[] WriteFull(object instance, bool isOwner)");
                sb.AppendLine($"            => {TypeDisplay2(m)}.__UniNetWriteFull(({TypeDisplay2(m)})instance, isOwner ? {TypeDisplay2(m)}.__UniNetFullMaskOwner : {TypeDisplay2(m)}.__UniNetFullMaskOther);");
                sb.AppendLine();
                sb.AppendLine("        public override void ApplyDelta(object instance, ref global::MessageProtocol.Serialize.MessageBufferReader reader)");
                sb.AppendLine($"            => {TypeDisplay2(m)}.__UniNetApplyIn(({TypeDisplay2(m)})instance, ref reader);");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
            sb.AppendLine("}");
        }

        static string SnapshotFields(TypeModel m)
        {
            var parts = new List<string>();
            foreach (var f in m.ReplicatedFields)
                parts.Add($"o.{f.Name}");
            return string.Join(", ", parts);
        }

        internal enum MaskUse { Delta, Full }

        /// <summary>Sendable field mask per receiving audience — deltas exclude InitialOnly, full state includes it.</summary>
        static uint DeltaMask(TypeModel m, MaskUse use, bool owner)
        {
            uint mask = 0;
            foreach (var f in m.ReplicatedFields)
            {
                if (use == MaskUse.Delta && f.IsInitialOnly) continue;
                if (owner ? f.IsSkipOwner : f.IsOwnerOnly) continue;
                mask |= 1u << f.Index;
            }
            return mask;
        }

