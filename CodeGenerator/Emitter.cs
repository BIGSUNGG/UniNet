        /// <summary>Public entry point for SafeName (used when emitting handlers).</summary>
        public static string SafeNameOf(TypeModel m)
        {
            var sb = new System.Text.StringBuilder(m.FullName.Length);
            foreach (var c in m.FullName)
                sb.Append(char.IsLetterOrDigit(c) ? c : '_');
            return sb.ToString();
        }

