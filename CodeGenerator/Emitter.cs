        static void EmitRequestedHandler(StringBuilder sb, TypeModel m, RpcModel rpc, string side)
        {
            string dispatchPrefix = rpc.Kind == RpcKind.Multicast ? "__UniNetClientDispatch_Multicast_" : "__UniNetClientDispatch_";
            string callArgs = rpc.Parameters.Count > 0 ? ", " + ArgList(rpc) : "";
            string envSlot = side == "Server" ? $"{Env}.Server" : $"{Env}.Client";

            string reqName = $"__Req_{SafeNameOf(m)}_{rpc.Name}";
            sb.AppendLine($"        internal static {TaskOfBytes} {reqName}(long senderConnId, byte[] data)");
            sb.AppendLine("        {");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            sb.AppendLine($"                var r = new {Reader}(data);");
            sb.AppendLine("                ulong netId = r.ReadUInt64();");
            sb.AppendLine("                byte subId = r.ReadByte();");
            foreach (var p in rpc.Parameters)
            {
                if (p.IsMessage)
                    sb.AppendLine($"                var {p.Name} = ({KeywordOrGlobal(p.Type)})global::MessageProtocol.Serialize.MessageSerializer.DeserializeFromReader(ref r);");
                else
                    sb.AppendLine($"                var {p.Name} = r.{ReadCall(p.Type)}();");
            }
            sb.AppendLine($"                var o = {envSlot}?.Get(netId, subId) as {TypeDisplay2(m)};");
            sb.AppendLine("                if (o != null)");
            if (rpc.Kind == RpcKind.Server)
            {
                string dispatchCall = $"{TypeDisplay2(m)}.__UniNetServerDispatch_{rpc.Name}(o, senderConnId{callArgs})";
                if (rpc.HasValidate)
                    sb.AppendLine($"                    {Env}.QueueOnMain(async () => await {dispatchCall});");
                else
                    sb.AppendLine($"                    {Env}.QueueOnMain(() => {dispatchCall});");
            }
            else
                sb.AppendLine($"                    {Env}.QueueOnMain(() => {TypeDisplay2(m)}.{dispatchPrefix}{rpc.Name}(o{callArgs}));");
            sb.AppendLine($"                return global::System.Threading.Tasks.Task.FromResult({Empty});");
            sb.AppendLine("            }");
            sb.AppendLine("            catch (global::System.Exception ex)   // malformed/short payload — isolated per connection");
            sb.AppendLine("            {");
            sb.AppendLine("                UnityEngine.Debug.LogException(ex);");
            sb.AppendLine($"                return global::System.Threading.Tasks.Task.FromResult({Empty});");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        static void EmitFireAndForget(StringBuilder sb)
        {
            // After Stop/reconnect, leftover sends on an already-closed session fail with InvalidOperationException —
            // benign shutdown noise with no functional impact, so downgrade to a warning; other exceptions keep their level (never swallowed).
            sb.AppendLine("        private void FireAndForget(global::System.Threading.Tasks.Task task)");
            sb.AppendLine("            => task.ContinueWith(t =>");
            sb.AppendLine("        {");
            sb.AppendLine("            var ex = t.Exception?.InnerException ?? (global::System.Exception)t.Exception;");
            sb.AppendLine("            if (ex is global::System.InvalidOperationException)");
            sb.AppendLine("                UnityEngine.Debug.LogWarning(\"[UniNet] 송신 실패(정지·재접속 경로의 정상 종료 노이즈): \" + ex.Message);");
            sb.AppendLine("            else");
            sb.AppendLine("                UnityEngine.Debug.LogException(ex);");
            sb.AppendLine("        }, global::System.Threading.Tasks.TaskContinuationOptions.OnlyOnFaulted);");
        }

