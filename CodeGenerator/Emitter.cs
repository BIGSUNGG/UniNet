        static string SnapshotFields(TypeModel m)
        {
            var parts = new List<string>();
            foreach (var f in m.ReplicatedFields)
            {
                if (f.IsCollection)
                {
                    // shadow snapshot — a List copy so element-level diffing works (FastArray, ADR-0020); null field counts as empty
                    parts.Add($"(o.{f.Name} == null ? new global::System.Collections.Generic.List<{KeywordOrGlobal(f.ElementType!)}>() : new global::System.Collections.Generic.List<{KeywordOrGlobal(f.ElementType!)}>(o.{f.Name}))");
                }
                else
                    parts.Add($"o.{f.Name}");
            }
            return string.Join(", ", parts);
        }

        internal enum MaskUse { Delta, Full }

        /// <summary>Sendable field mask per receiving audience — deltas exclude InitialOnly, full state includes it.</summary>
        static uint DeltaMask(TypeModel m, MaskUse use, bool owner)
        {
            uint mask = 0;
            foreach (var f in m.ReplicatedFields)
            {
                if (use == MaskUse.Delta && f.IsInitialOnly) continue;
                if (owner ? f.IsSkipOwner : f.IsOwnerOnly) continue;
                mask |= 1u << f.Index;
            }
            return mask;
        }

